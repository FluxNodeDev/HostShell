const DICTS: Record<Locale, Dict> = {
  en,
  'zh-CN': zh,
  ja,
  ko,
  de,
  fr,
  es,
  ru,
  'pt-BR': pt
}

/** 浏览器/系统语言 -> 支持的语言 */
export function detectLocale(): Locale {
  const langs = [navigator.language, ...(navigator.languages || [])].filter(Boolean)
  for (const raw of langs) {
    const l = raw.toLowerCase()
    if (l.startsWith('zh')) return 'zh-CN'
    if (l.startsWith('pt')) return 'pt-BR'
    if (l.startsWith('ja')) return 'ja'
    if (l.startsWith('ko')) return 'ko'
    if (l.startsWith('de')) return 'de'
    if (l.startsWith('fr')) return 'fr'
    if (l.startsWith('es')) return 'es'
    if (l.startsWith('ru')) return 'ru'
    if (l.startsWith('en')) return 'en'
  }
  return 'en'
}

export function normalizeLocale(v: string | undefined): Locale {
  if (!v) return detectLocale()
  const hit = LOCALES.find((l) => l.id === v || l.id.toLowerCase() === v.toLowerCase())
  if (hit) return hit.id
  // 宽松匹配：zh-tw/zh-hk 归一到 zh-CN，pt 归一到 pt-BR
  const low = v.toLowerCase()
  if (low.startsWith('zh')) return 'zh-CN'
  if (low.startsWith('pt')) return 'pt-BR'
  const prefix = low.split('-')[0]
  const byPrefix = LOCALES.find((l) => l.id.split('-')[0] === prefix)
  return byPrefix ? byPrefix.id : 'en'
}

export function translate(
  locale: Locale,
  key: string,
  vars?: Record<string, string | number>
): string {
  const dict = DICTS[locale] || en
  let text = dict[key] ?? en[key] ?? key
  if (vars) {
    for (const [k, v] of Object.entries(vars)) {
      text = text.replace(new RegExp(`\\{${k}\\}`, 'g'), String(v))
    }
  }
  return text
}

/** 运行时长本地化：zh 用中文单位，其余用 h/m/d 简写 */

const UNITS = {
  zh: { d: '\u5929', h: '\u5c0f\u65f6', m: '\u5206', sep: '' },
  ja: { d: '\u65e5', h: '\u6642\u9593', m: '\u5206', sep: '' },
  ko: { d: '\uc77c', h: '\uc2dc\uac04', m: '\ubd84', sep: ' ' },
  en: { d: 'd', h: 'h', m: 'm', sep: ' ' }
}

/** 运行时长本地化：中文/日文用汉字单位，韩文与其它语言用简写 */
export function formatUptime(seconds: number, locale: Locale): string {
  const s = Math.max(0, Math.floor(seconds))
  const d = Math.floor(s / 86400)
  const h = Math.floor((s % 86400) / 3600)
  const m = Math.floor((s % 3600) / 60)
  const u = locale === 'zh-CN' ? UNITS.zh : locale === 'ja' ? UNITS.ja : locale === 'ko' ? UNITS.ko : UNITS.en
  if (d > 0) return `${d}${u.d}${u.sep}${h}${u.h}`
  if (h > 0) return `${h}${u.h}${u.sep}${m}${u.m}`
  return `${m}${u.m}`
}